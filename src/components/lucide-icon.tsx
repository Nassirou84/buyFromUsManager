type Props = {
  name: string;
  className?: string;
  style?: CSSProperties;
};

// Size comes from the existing `text-[Npx]` class so call sites keep their sizing.
const SIZE_CLASS = /text-\[(\d+)px\]/;

export function Icon({ name, className = '', style }: Props) {
  const Cmp = ICONS[name] ?? CircleHelp;
  const size = Number(className.match(SIZE_CLASS)?.[1] ?? 24);
  const rest = className.replace(SIZE_CLASS, '').trim();

  return <Cmp size={size} className={`shrink-0 ${rest}`} style={style} aria-hidden />;
}
